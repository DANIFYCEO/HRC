// Helper function to get today's reading
export const getTodayReading = (startDate: Date): ReadingDay | null => {
  const today = new Date();
  const diffTime = Math.abs(today.getTime() - startDate.getTime());
  const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));

  if (diffDays > 365) {
    return null; // Plan completed
  }

  return BIBLE_ONE_YEAR_PLAN[diffDays - 1] || null;
};

// Calculate progress percentage
export const calculateProgress = (completedDays: number[]): number => {
  return Math.round((completedDays.length / 365) * 100);
};

// Calculate current streak
export const calculateStreak = (completedDays: number[], startDate: Date): number => {
  const today = new Date();
  const diffTime = Math.abs(today.getTime() - startDate.getTime());
  const currentDay = Math.ceil(diffTime / (1000 * 60 * 60 * 24));

  let streak = 0;
  for (let i = currentDay; i >= 1; i--) {
    if (completedDays.includes(i)) {
      streak++;
    } else {
      break;
    }
  }

  return streak;
};

